namespace ComplexityResearch.Models;

/// <summary>
/// Режим измерения для конкретного значения n.
/// </summary>
/// <remarks>
/// <para>
/// <see cref="Direct"/> — алгоритм физически обрабатывает массив размера n
/// (массив реально выделен в памяти).
/// </para>
/// <para>
/// <see cref="Scaled"/> — логический размер задачи равен n, но физически
/// алгоритм многократно обрабатывает массив фиксированного (меньшего) размера,
/// выполняя количество проходов, пропорциональное n. Это позволяет измерять
/// линейные алгоритмы для n = 10^8...3·10^9 без выделения массивов на десятки
/// гигабайт. Результат такого измерения НЕ является полным физическим
/// измерением обработки n элементов и всегда помечается в таблице и отчёте.
/// </para>
/// </remarks>
public enum MeasurementMode
{
    /// <summary>Прямой режим: реальный массив размера n.</summary>
    Direct,

    /// <summary>Масштабированный режим: блок фиксированного размера, повторённый n/размер_блока раз.</summary>
    Scaled
}
